// SaleBadge is a SALE -n% starburst whose rim flashes.
func SaleBadge(c *ui.Context, percent int, o SaleBadgeOptions) *ui.Element {
	k := pixel.K(c)
	if percent < 1 || percent > 99 {
		panic(fmt.Sprintf("shop: SaleBadge of %d%%", percent))
	}
	sale, off := k.Msg("sale"), "-"+strconv.Itoa(percent)+"%"
	return ui.Box(c).Size(k.D(burst.W), k.D(burst.H)).Role(ui.RoleImage).Label(sale + " " + off).Draw(func(p *ui.Painter, r ui.Rect) {
		g := k.Canvas(p, r)
		g.Sprite(0, 0, burst, 0, pixel.Bad, 1)
		// Each second the rim turns gold, unless motion is reduced.
		if g.Step(4)/4%2 == 1 {
			g.Sprite(0, 0, rim, 0, pixel.Warn, 1)
		}
		g.Text((burst.W-pixel.Measure(sale))/2, 8, sale, pixel.Lit, 1)
		g.Text((burst.W-pixel.Measure(off))/2, 24, off, pixel.Lit, 1)
	})
}
